package org.kuali.rice.kns.datadictionary;
public class HeaderNavigation {
    private String headerTabMethodToCall;
    private String headerTabNavigateTo;
    private String headerTabDisplayName;
    public HeaderNavigation() {}
    public String getHeaderTabMethodToCall() { return headerTabMethodToCall; }
    public void setHeaderTabMethodToCall(String s) { this.headerTabMethodToCall = s; }
    public String getHeaderTabNavigateTo() { return headerTabNavigateTo; }
    public void setHeaderTabNavigateTo(String s) { this.headerTabNavigateTo = s; }
    public String getHeaderTabDisplayName() { return headerTabDisplayName; }
    public void setHeaderTabDisplayName(String s) { this.headerTabDisplayName = s; }
}

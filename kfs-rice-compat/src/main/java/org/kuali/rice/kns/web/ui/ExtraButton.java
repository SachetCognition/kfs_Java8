package org.kuali.rice.kns.web.ui;

public class ExtraButton {
    private String extraButtonSource;
    private String extraButtonAltText;
    private String extraButtonParams;
    private String extraButtonProperty;
    private String extraButtonOnclick;
    
    public ExtraButton() {}
    
    public String getExtraButtonSource() { return extraButtonSource; }
    public void setExtraButtonSource(String source) { this.extraButtonSource = source; }
    public String getExtraButtonAltText() { return extraButtonAltText; }
    public void setExtraButtonAltText(String altText) { this.extraButtonAltText = altText; }
    public String getExtraButtonParams() { return extraButtonParams; }
    public void setExtraButtonParams(String params) { this.extraButtonParams = params; }
    public String getExtraButtonProperty() { return extraButtonProperty; }
    public void setExtraButtonProperty(String property) { this.extraButtonProperty = property; }
    public String getExtraButtonOnclick() { return extraButtonOnclick; }
    public void setExtraButtonOnclick(String onclick) { this.extraButtonOnclick = onclick; }
}
